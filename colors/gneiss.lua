-- Gneiss for Neovim: Nord's colors on neutral grays.
--
-- A hard fork of gbprod/nord.nvim (see NOTICE). Its highlights were taken
-- once, with its default options, and Nord's colors swapped for the base
-- colors in palette.toml; they are Gneiss's own from here on. The build
-- fills in each base color named in double braces.
--
-- One change from Nord: terminal color 8 (bright black) is the comment gray,
-- as in the Alacritty and VS Code ports, so it stays readable on the
-- background.

