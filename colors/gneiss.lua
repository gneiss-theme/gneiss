-- Mixes a color into the background by the given amount, for tinted
-- backgrounds and dimmed text.
local background = "#1C1C1C"
local function darken(color, amount)
  local function mix(i)
    local fg, bg = tonumber(color:sub(i, i + 1), 16), tonumber(background:sub(i, i + 1), 16)
    return math.floor(amount * fg + (1 - amount) * bg + 0.5)
  end
  return ("#%02x%02x%02x"):format(mix(2), mix(4), mix(6))
end

